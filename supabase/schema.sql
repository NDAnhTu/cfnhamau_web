-- 1. BẢNG PROFILES & TRIGGER ĐỒNG BỘ AUTH
create table if not exists public.profiles (
  id uuid references auth.users(id) on delete cascade primary key,
  full_name text not null,
  role text not null check (role in ('owner', 'staff')),
  phone text,
  is_active boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- Tự động thêm hồ sơ khi tài khoản mới được đăng ký trên Supabase Auth
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, full_name, role, phone)
  values (
    new.id, 
    coalesce(new.raw_user_meta_data->>'full_name', 'Nhân viên mới'), 
    coalesce(new.raw_user_meta_data->>'role', 'staff'),
    new.raw_user_meta_data->>'phone'
  )
  on conflict (id) do update set
    full_name = coalesce(excluded.full_name, profiles.full_name),
    role = coalesce(excluded.role, profiles.role);
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- 2. BẢNG DANH MỤC (CATEGORIES)
create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  display_order int default 0,
  is_active boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 3. BẢNG SẢN PHẨM / MÓN (PRODUCTS)
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id) on delete set null,
  name text not null,
  has_sizes boolean default false,
  base_price numeric(12, 2) default 0 check (base_price >= 0),
  image_url text,
  is_available boolean default true,
  is_active boolean default true,
  is_quick_created boolean default false,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 4. BẢNG KÍCH CỠ VÀ GIÁ (PRODUCT_SIZES)
create table if not exists public.product_sizes (
  id bigint generated by default as identity primary key,
  product_id bigint references public.products(id) on delete cascade not null,
  size_name text not null,
  price numeric(12, 2) not null check (price >= 0),
  is_available boolean default true,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- 5. BẢNG BÀN & KHU VỰC (TABLES)
create table if not exists public.tables (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_occupied boolean default false
);

-- 6. BẢNG CA LÀM VIỆC & KIỂM KÉT (SHIFTS)
create table if not exists public.shifts (
  id bigint generated by default as identity primary key,
  staff_id uuid references public.profiles(id) not null,
  start_time timestamptz default timezone('utc'::text, now()) not null,
  end_time timestamptz,
  starting_cash numeric(12, 2) default 0,
  ending_cash_system numeric(12, 2),
  ending_cash_actual numeric(12, 2),
  difference numeric(12, 2),
  status text default 'open' check (status in ('open', 'closed')),
  notes text
);

-- 7. BẢNG HÓA ĐƠN / ĐƠN HÀNG (ORDERS)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  shift_id bigint references public.shifts(id) on delete set null,
  order_number text not null,
  table_id bigint references public.tables(id) on delete restrict,
  order_type text default 'dine_in' check (order_type in ('dine_in', 'takeaway')),
  created_by uuid references public.profiles(id),
  status text default 'pending' check (status in ('pending', 'completed', 'cancelled')),
  payment_method text default 'cash' check (payment_method in ('cash', 'vietqr')),
  total_amount numeric(12, 2) not null check (total_amount >= 0),
  discount_amount numeric(12, 2) default 0 check (discount_amount >= 0),
  final_amount numeric(12, 2) not null check (final_amount >= 0),
  notes text,
  cancel_reason text,
  cancelled_by uuid references public.profiles(id),
  created_at timestamptz default timezone('utc'::text, now()) not null,
  completed_at timestamptz
);

-- 8. BẢNG CHI TIẾT TỪNG MÓN TRONG ĐƠN (ORDER_ITEMS)
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint references public.orders(id) on delete cascade not null,
  product_id bigint references public.products(id) on delete set null,
  product_size_id bigint references public.product_sizes(id) on delete set null,
  item_name text not null,
  size_name text,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity int not null check (quantity > 0),
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  notes text,
  is_custom boolean default false,
  status text default 'active' check (status in ('active', 'cancelled')),
  cancel_reason text
);

-- 9. BẢNG SỔ QUỸ THU CHI NGOÀI (CASH_TRANSACTIONS)
create table if not exists public.cash_transactions (
  id bigint generated by default as identity primary key,
  shift_id bigint references public.shifts(id) on delete set null,
  type text not null check (type in ('income', 'expense')),
  category text not null, -- tien_da, dien_nuoc, nguyen_lieu_phu, mat_bang, khac
  amount numeric(12, 2) not null check (amount > 0),
  description text not null,
  created_by uuid references public.profiles(id),
  transaction_date date default current_date not null,
  created_at timestamptz default timezone('utc'::text, now()) not null
);

-- ============================================================
-- TẠO INDEXES TỐI ƯU TRUY VẤN
-- ============================================================
create index if not exists idx_orders_shift on public.orders(shift_id);
create index if not exists idx_orders_created_at on public.orders(created_at);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_order_items_order on public.order_items(order_id);
create index if not exists idx_product_sizes_product on public.product_sizes(product_id);
create index if not exists idx_cash_transactions_shift on public.cash_transactions(shift_id);
create index if not exists idx_cash_transactions_date on public.cash_transactions(transaction_date);

